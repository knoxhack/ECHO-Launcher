import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import crypto from 'node:crypto'

const launcherRoot = path.resolve(import.meta.dirname, '..')
const workspaceRoot = path.resolve(launcherRoot, '..')
const androidRoot = path.join(workspaceRoot, 'ECHO-Command-Android')
const reportsDir = path.join(launcherRoot, 'reports')
const verificationPath = path.join(reportsDir, 'mobile-rc-verification.json')
const acceptancePath = path.join(reportsDir, 'mobile-manual-acceptance.json')
const packagePath = path.join(reportsDir, 'mobile-rc-package.json')
const packageScriptPath = path.join(launcherRoot, 'scripts', 'mobile-rc-package.mjs')
const androidApkPath = path.join(androidRoot, 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk')
const packagedCurrentSources = [
  {
    id: 'desktop-beta-guide',
    path: path.join(launcherRoot, 'docs', 'mobile-command-center-beta.md'),
    label: 'desktop beta guide',
  },
  {
    id: 'desktop-rc-guide',
    path: path.join(launcherRoot, 'docs', 'mobile-beta-release-candidate.md'),
    label: 'desktop RC guide',
  },
  {
    id: 'android-beta-guide',
    path: path.join(androidRoot, 'docs', 'beta-mobile-pairing.md'),
    label: 'Android beta guide',
  },
  {
    id: 'manual-acceptance-template',
    path: path.join(launcherRoot, 'docs', 'mobile-manual-acceptance-template.json'),
    label: 'manual acceptance template',
  },
]
const tagIndex = process.argv.indexOf('--tag')
const requestedTag = tagIndex >= 0 ? process.argv[tagIndex + 1] : ''
const requiredAcceptanceCheckIds = [
  'apk-installed',
  'qr-pairing',
  'desktop-approval',
  'auto-finish-pairing',
  'live-data',
  'launch-action',
  'update-action',
  'repair-action',
  'scan-install-action',
  'packos-check-action',
  'support-bundle-action',
  'duplicate-operation-guard',
  'desktop-diagnostics-copied',
  'android-diagnostics-copied',
]

function readJson(filePath, label, failures) {
  if (!existsSync(filePath)) {
    failures.push(`${label} is missing: ${filePath}`)
    return null
  }
  try {
    return JSON.parse(readFileSync(filePath, 'utf8'))
  } catch (error) {
    failures.push(`${label} is not valid JSON: ${error instanceof Error ? error.message : String(error)}`)
    return null
  }
}

function runGit(args) {
  return spawnSync('git', args, {
    cwd: launcherRoot,
    encoding: 'utf8',
    shell: true,
  })
}

function fileSha256(filePath) {
  return crypto.createHash('sha256').update(readFileSync(filePath)).digest('hex')
}

function packageFile(packageReport, fileId) {
  return Array.isArray(packageReport?.files)
    ? packageReport.files.find((file) => file.id === fileId)
    : null
}

const failures = []
const verification = readJson(verificationPath, 'Automated RC verification report', failures)
const acceptance = readJson(acceptancePath, 'Manual phone acceptance report', failures)
const packageReport = readJson(packagePath, 'Mobile RC package report', failures)

if (verification) {
  if (verification.passed !== true) failures.push('Automated RC verification did not pass')
  if (verification.runChecks !== true) failures.push('Automated RC verification must come from npm.cmd run rc:mobile, not quick mode')
  const failedChecks = Array.isArray(verification.checks) ? verification.checks.filter((check) => check.ok !== true) : []
  if (failedChecks.length) failures.push(`Automated RC verification has failed checks: ${failedChecks.map((check) => check.id).join(', ')}`)
}

if (packageReport) {
  if (packageReport.passed !== true) failures.push('Mobile RC package did not pass')
  const verificationGeneratedAt = Date.parse(String(verification?.generatedAt ?? ''))
  const packageGeneratedAt = Date.parse(String(packageReport.generatedAt ?? ''))
  if (Number.isFinite(verificationGeneratedAt) && Number.isFinite(packageGeneratedAt) && packageGeneratedAt < verificationGeneratedAt) {
    failures.push('Mobile RC package is older than the latest automated verification; rerun npm.cmd run rc:mobile:package')
  }
  if (Number.isFinite(packageGeneratedAt) && existsSync(packageScriptPath) && packageGeneratedAt < statSync(packageScriptPath).mtimeMs) {
    failures.push('Mobile RC package is older than the package generator script; rerun npm.cmd run rc:mobile:package')
  }
  const currentPackageScriptSha256 = existsSync(packageScriptPath) ? fileSha256(packageScriptPath) : ''
  const packagedGeneratorSha256 = String(packageReport.packageGenerator?.sha256 ?? '').toLowerCase()
  if (!packagedGeneratorSha256) {
    failures.push('Mobile RC package is missing the package generator checksum; rerun npm.cmd run rc:mobile:package')
  } else if (currentPackageScriptSha256 && packagedGeneratorSha256 !== currentPackageScriptSha256) {
    failures.push('Mobile RC package was not generated by the current package generator script; rerun npm.cmd run rc:mobile:package')
  }
  const zipPath = String(packageReport.zipPath ?? '')
  const checksumPath = String(packageReport.checksumPath ?? '')
  const expectedZipSha256 = String(packageReport.zipSha256 ?? '').toLowerCase()
  if (!zipPath || !existsSync(zipPath)) {
    failures.push(`Mobile RC package zip is missing: ${zipPath || '(not recorded)'}`)
  } else {
    const actualZipSha256 = fileSha256(zipPath)
    if (expectedZipSha256 && actualZipSha256 !== expectedZipSha256) {
      failures.push(`Mobile RC package zip checksum mismatch: expected ${expectedZipSha256}, got ${actualZipSha256}`)
    }
  }
  if (!checksumPath || !existsSync(checksumPath)) {
    failures.push(`Mobile RC package checksum file is missing: ${checksumPath || '(not recorded)'}`)
  } else if (expectedZipSha256) {
    const checksumText = readFileSync(checksumPath, 'utf8').toLowerCase()
    if (!checksumText.includes(expectedZipSha256)) {
      failures.push('Mobile RC package checksum file does not contain the recorded zip SHA-256')
    }
  }
  const packagedVerification = packageFile(packageReport, 'rc-verification-json')
  const packagedAndroidApk = packageFile(packageReport, 'android-apk')
  if (packagedVerification && existsSync(verificationPath)) {
    const currentVerificationSha256 = fileSha256(verificationPath)
    if (String(packagedVerification.sha256 ?? '').toLowerCase() !== currentVerificationSha256) {
      failures.push('Mobile RC package does not contain the current automated verification report; rerun npm.cmd run rc:mobile:package')
    }
  } else {
    failures.push('Mobile RC package is missing the packaged automated verification checksum')
  }
  if (packagedAndroidApk && existsSync(androidApkPath)) {
    const currentApkSha256 = fileSha256(androidApkPath)
    if (String(packagedAndroidApk.sha256 ?? '').toLowerCase() !== currentApkSha256) {
      failures.push('Mobile RC package does not contain the current Android APK; rerun npm.cmd run rc:mobile:package')
    }
  } else {
    failures.push('Mobile RC package is missing the packaged Android APK checksum')
  }
  for (const source of packagedCurrentSources) {
    const packaged = packageFile(packageReport, source.id)
    if (!packaged) {
      failures.push(`Mobile RC package is missing the packaged ${source.label} checksum`)
      continue
    }
    if (!existsSync(source.path)) {
      failures.push(`Current ${source.label} is missing: ${source.path}`)
      continue
    }
    const currentSha256 = fileSha256(source.path)
    if (String(packaged.sha256 ?? '').toLowerCase() !== currentSha256) {
      failures.push(`Mobile RC package does not contain the current ${source.label}; rerun npm.cmd run rc:mobile:package`)
    }
  }
}

if (acceptance) {
  if (acceptance.passed !== true) failures.push('Manual phone acceptance did not pass')
  const accepted = acceptance.acceptance ?? {}
  const acceptedChecks = Array.isArray(accepted.checks) ? accepted.checks : []
  const acceptedById = new Map(acceptedChecks.map((check) => [String(check.id ?? ''), check]))
  const missingRequiredChecks = requiredAcceptanceCheckIds.filter((id) => !acceptedById.has(id))
  if (missingRequiredChecks.length) {
    failures.push(`Manual phone acceptance is missing required checks: ${missingRequiredChecks.join(', ')}`)
  }
  const missingChecks = Array.isArray(accepted.checks)
    ? accepted.checks.filter((check) => String(check.status ?? '').toLowerCase() !== 'pass')
    : []
  if (missingChecks.length) failures.push(`Manual phone acceptance has non-pass checks: ${missingChecks.map((check) => check.id).join(', ')}`)
}

const packageJson = JSON.parse(readFileSync(path.join(launcherRoot, 'package.json'), 'utf8'))
const defaultTag = `mobile-command-center-v${packageJson.version}`
const tagName = requestedTag || defaultTag
let tagged = false

if (!failures.length && requestedTag) {
  const existing = runGit(['rev-parse', '-q', '--verify', `refs/tags/${requestedTag}`])
  if (existing.status === 0) {
    failures.push(`Git tag already exists: ${requestedTag}`)
  } else {
    const tag = runGit([
      'tag',
      '-a',
      requestedTag,
      '-m',
      `Mobile Command Center RC accepted ${new Date().toISOString()}`,
    ])
    if (tag.status !== 0) {
      failures.push(`Failed to create git tag ${requestedTag}: ${tag.stderr || tag.stdout}`)
    } else {
      tagged = true
    }
  }
}

mkdirSync(reportsDir, { recursive: true })
const generatedAt = new Date().toISOString()
const report = {
  generatedAt,
  ready: failures.length === 0,
  tagName,
  tagged,
  failures,
  verificationReport: verificationPath,
  acceptanceReport: acceptancePath,
  packageReport: packagePath,
  androidApk: androidApkPath,
}
const jsonPath = path.join(reportsDir, 'mobile-rc-ready.json')
const markdownPath = path.join(reportsDir, 'mobile-rc-ready.md')
writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`)
writeFileSync(
  markdownPath,
  [
    '# Mobile RC Ready Gate',
    '',
    `Generated: ${generatedAt}`,
    `Status: ${report.ready ? 'READY' : 'NOT READY'}`,
    `Tag: ${tagName}`,
    `Tagged: ${tagged ? 'yes' : 'no'}`,
    '',
    '## Required Evidence',
    '',
    `- Automated RC verification: ${verificationPath}`,
    `- Uploadable RC package: ${packagePath}`,
    `- Current Android APK: ${androidApkPath}`,
    `- Manual phone acceptance: ${acceptancePath}`,
    '',
    '## Failures',
    '',
    ...(failures.length ? failures.map((failure) => `- ${failure}`) : ['- none']),
    '',
    '## Tag Command',
    '',
    requestedTag
      ? `Requested tag: ${requestedTag}`
      : `When ready, run: npm.cmd run rc:mobile:ready -- --tag ${defaultTag}`,
    '',
  ].join('\n'),
)

console.log(`Mobile RC ready gate ${report.ready ? 'READY' : 'NOT READY'}`)
console.log(`JSON: ${jsonPath}`)
console.log(`Markdown: ${markdownPath}`)
process.exit(report.ready ? 0 : 1)
